"""Read declared slicer statistics and explicit temperature commands; never execute G-code."""

import collections
import hashlib
import math
import re

from .storage import Files


def duration(text: str) -> float | None:
    parts = re.findall(r"(\d+(?:\.\d+)?)\s*([dhms])", text)
    return (
        sum(float(n) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit] for n, unit in parts)
        if parts
        else None
    )


def analyze(files: Files, path: str) -> dict:
    target = files.path(path, True)
    if target.suffix.lower() not in (".gcode", ".gco", ".gc"):
        raise ValueError(
            "Only plain-text G-code is supported; binary BGCode must be exported as text"
        )
    sha = hashlib.sha256()
    counts = collections.Counter()
    features = collections.Counter()
    config = {}
    stats = {}
    declared_times = {}
    temperatures = {"nozzle": set(), "bed": set()}
    observed_layers = set()
    generator = None
    lines = 0
    config_block = False
    with target.open("rb") as stream:
        for raw in stream:
            sha.update(raw)
            lines += 1
            line = raw.decode("utf-8", errors="replace").strip()
            if line.startswith("; CONFIG_BLOCK_START"):
                config_block = True
            elif line.startswith("; CONFIG_BLOCK_END"):
                config_block = False
            if line.startswith(";"):
                text = line.lstrip("; ")
                if text.startswith("generated by "):
                    generator = text[len("generated by ") :]
                if "total estimated time:" in text:
                    for label, value in re.findall(
                        r"(model printing time|total estimated time):\s*([^;]+)", text
                    ):
                        declared_times[label] = duration(value)
                if text.startswith("estimated printing time") and "=" in text:
                    label, value = text.split("=", 1)
                    declared_times[label.strip()] = duration(value)
                if config_block and " = " in text:
                    key, value = text.split(" = ", 1)
                    if key in {
                        "layer_height",
                        "initial_layer_print_height",
                        "sparse_infill_density",
                        "wall_loops",
                        "printer_model",
                        "printer_settings_id",
                        "print_settings_id",
                        "filament_type",
                        "filament_settings_id",
                        "nozzle_diameter",
                    }:
                        config[key] = value
                if re.match(r"(?:filament used \[(?:mm|cm3|g)\]|filament cost)\s*=", text):
                    key, value = text.split("=", 1)
                    try:
                        numbers = [float(v.strip()) for v in value.split(",")]
                        if all(math.isfinite(v) for v in numbers):
                            stats[key.strip()] = numbers
                    except ValueError:
                        pass
                if match := re.match(r"total layer number:\s*(\d+)", text):
                    stats["declared_layers"] = int(match[1])
                if match := re.match(r"layer num/total_layer_count:\s*(\d+)/(\d+)", text):
                    observed_layers.add(int(match[1]))
                if match := re.match(r"(?:TYPE|FEATURE):\s*(.*)", text):
                    features[match[1]] += 1
                continue
            command = re.sub(r"^N\d+\s*", "", line).split(";", 1)[0]
            match = re.match(r"^([GMT]\d+(?:\.\d+)?)\b", command, re.I)
            if not match:
                # Compact commands such as G1X10 are valid, so do not require a word boundary.
                match = re.match(r"^([GMT]\d+(?:\.\d+)?)", command, re.I)
            if match:
                code = match[1].upper()
                counts[code] += 1
                if code in {"M104", "M109", "M140", "M190"}:
                    params = re.findall(r"[SR]\s*(-?\d+(?:\.\d+)?)", command[match.end() :], re.I)
                    bucket = "nozzle" if code in {"M104", "M109"} else "bed"
                    for value in params:
                        number = float(value)
                        if math.isfinite(number):
                            temperatures[bucket].add(number)
    return {
        "path": str(target),
        "sha256": sha.hexdigest(),
        "bytes": target.stat().st_size,
        "lines": lines,
        "generator": generator,
        "estimated_seconds": declared_times,
        "declared_statistics": stats,
        "observed_layer_markers": len(observed_layers),
        "selected_settings": config,
        "commands": dict(counts.most_common()),
        "feature_sections": dict(features),
        "explicit_temperature_targets": {k: sorted(v) for k, v in temperatures.items()},
        "notice": "Declared estimates and explicit commands only; not a toolpath simulation, printer-safety verdict or actual print duration. Conditional macros and firmware behavior are not evaluated.",
    }
